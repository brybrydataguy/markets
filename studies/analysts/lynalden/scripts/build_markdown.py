"""Generate GitHub-readable reviews and guides from the canonical audit data."""
from collections import Counter
from html.parser import HTMLParser
from pathlib import Path
import json

from report_sections import glossary_section

ROOT = Path(__file__).resolve().parent.parent
DATA = ROOT / 'data'
NOTICE = '<!-- Generated by scripts/build_markdown.py. Edit data/ and rebuild. -->\n\n'
LABELS = {'right': 'Right', 'wrong': 'Wrong', 'mixed': 'Mixed',
          'too_early': 'Too early', 'not_testable': 'Not testable',
          'evidence_needed': 'Evidence needed', 'conditional_pending': 'Conditional pending'}


def load(name):
    return json.loads((DATA / name).read_text())


def write(name, content):
    (ROOT / name).write_text(NOTICE + content.rstrip() + '\n')


def cell(value):
    return str(value).replace('|', '\\|').replace('\n', '<br>')


def table(headers, rows):
    lines = ['| ' + ' | '.join(map(cell, headers)) + ' |',
             '| ' + ' | '.join('---' for _ in headers) + ' |']
    lines += ['| ' + ' | '.join(map(cell, row)) + ' |' for row in rows]
    return '\n'.join(lines) + '\n\n'


def links(ids):
    return 'Related reviews: ' + ', '.join(f'[{i}](articles/{i}.md)' for i in ids) + '.\n\n'


def bullets(items):
    if isinstance(items, str):
        items = [items]
    return ''.join('- ' + str(item) + '\n' for item in items) + '\n'


def finding(value):
    """Render stored return calculations while preserving any appended note."""
    try:
        data, end = json.JSONDecoder().raw_decode(value)
    except (TypeError, ValueError):
        return str(value)
    if not isinstance(data, dict) or not isinstance(data.get('instruments'), dict):
        return value
    result = f"Observed window: {data.get('entry')} to {data.get('exit')}. Requested endpoint: {data.get('requested_endpoint')}.\n\n"
    fields = ['entry_adjusted_close', 'exit_adjusted_close', 'cumulative_return_pct', 'annualized_return_pct']
    rows = []
    for symbol, values in data['instruments'].items():
        row = [symbol]
        for key in fields:
            v = values.get(key)
            row.append(f'{v:,.2f}' if isinstance(v, (int, float)) else 'Not available')
        rows.append(row)
    result += table(['Instrument', 'Entry adjusted price', 'Exit adjusted price', 'Return (%)', 'Annualized (%)'], rows)
    if data.get('endpoint_covered') is False:
        result += f"Incomplete coverage: last observation is {data.get('endpoint_gap_days')} days before the requested endpoint.\n\n"
    result += data.get('method', '')
    if value[end:].strip():
        result += '\n\n' + value[end:].strip()
    return result


reviews = [json.loads(p.read_text()) for p in sorted((DATA / 'reviews').glob('[0-9][0-9][0-9].json'))]
syn = load('synthesis.json')
method = load('methodology.json')
counts = Counter(c['verdict'] for r in reviews for c in r['claims'])

for review in reviews:
    aid = review['article_id']
    text = f"# {review['title']}\n\n"
    text += f"Report {aid} | Published {review['date']} | Evaluated {review.get('evaluation_as_of', method['as_of'])}\n\n"
    text += f"[Original member article]({review['source_url']}) | [Article index](README.md) | [Structured review](../data/reviews/{aid}.json)\n\n"
    text += review.get('summary', '') + '\n\n' + review.get('assessment', '') + '\n\n'
    text += '**Coverage:** ' + review.get('coverage_note', '') + '\n\n'
    text += '## Claims\n\n'
    for claim in review['claims']:
        text += f"### {claim['id']}\n\n**{claim['claim']}**\n\n"
        text += table(['Field', 'Assessment'], [
            ('Verdict', LABELS[claim['verdict']]),
            ('Type', claim.get('kind', '').replace('_', ' ')),
            ('Horizon', claim.get('horizon') or 'Not specified'),
            ('Conditions', claim.get('conditions') or 'Not specified'),
            ('Author modality', claim.get('modality') or 'Not specified'),
            ('Asset or variable', claim.get('asset_or_variable') or 'Not specified'),
            ('Source blocks', ', '.join(map(str, claim.get('source_blocks', [])))),
            ('Thesis family', claim.get('family', 'Unclassified')),
        ])
        text += claim.get('reason', '') + '\n\n'
        for key, label in [('direction_assessment', 'Direction'), ('timing_assessment', 'Timing'),
                           ('mechanism_assessment', 'Mechanism'), ('confidence', 'Reviewer confidence'),
                           ('next_check', 'Next test')]:
            if claim.get(key):
                text += f"**{label}:** {claim[key]}\n\n"
        if claim.get('proof'):
            proof = claim['proof']
            text += '**Deductive assessment:**\n\n'
            text += bullets(proof.get('assumptions', [])) + proof.get('derivation', '') + '\n\n'
        text += '**Outcome evidence:**\n\n'
        if not claim.get('evidence'):
            text += 'No independent outcome source is recorded. Any deductive assessment is identified separately.\n\n'
        for e in claim.get('evidence', []):
            label = e.get('title') or e.get('publisher') or 'Source'
            text += f"- [{label}]({e['url']})"
            if e.get('publisher'):
                text += ' | ' + e['publisher']
            if e.get('date'):
                text += ' | ' + e['date']
            text += ' | ' + ('Verified in the audit' if e.get('verified') else 'Not independently verified') + '\n\n'
            text += finding(e.get('finding', '')) + '\n\n'
    text += '## Analytical tools and charts\n\n'
    for tool in review.get('tools_charts', []):
        text += f"- **{tool['name']}:** {tool.get('use', '')}"
        text += ' Visual inspection: ' + ('yes' if tool.get('image_inspected') else 'not performed') + '.\n'
    text += '\n## Framework lessons\n\n' + bullets(review.get('framework_lessons', []))
    text += '## Verification limitations\n\n' + bullets(review.get('verification_limitations', []))
    text += f"[Back to article index](README.md) | [Overall summary](../SUMMARY.md)\n"
    write(f'articles/{aid}.md', text)

index = '# Article index\n\nOne review per article, in publication order. All 200 reviews are available.\n\n[Start here](../README.md) | [Overall summary](../SUMMARY.md)\n\n'
index += table(['Report', 'Published', 'Article', 'Claims'],
               [(r['article_id'], r['date'], f"[{r['title']}]({r['article_id']}.md)", len(r['claims'])) for r in reviews])
write('articles/README.md', index)

summary = '# Overall summary\n\nAs of ' + syn['as_of'] + '.\n\n' + syn['summary']['headline'] + '\n\n'
summary += '\n\n'.join(syn['summary']['paragraphs']) + '\n\n'
summary += '## Assessment by dimension\n\n'
for item in syn['summary']['dimensions']:
    summary += f"### {item['name']}\n\n**{item['judgment']}**\n\n{item['text']}\n\n" + links(item['article_ids'])
summary += '## Major episodes\n\nSelected consequential episodes, not independent observations or an exhaustive episode count.\n\n'
for item in syn['episodes']:
    summary += f"### {item['title']}\n\n**{item['outcome']}**\n\n{item['text']}\n\n" + links(item['article_ids'])
summary += '## Coverage\n\n' + table(['Verdict', 'Claim occurrences'], [(LABELS[k], v) for k, v in counts.items()])
summary += f"Total: {len(reviews)} article reviews and {sum(counts.values()):,} claim occurrences. Evidence gaps remain explicit; these counts are not a forecasting accuracy percentage or portfolio track record.\n"
write('SUMMARY.md', summary)

framework = '# How would Lyn think about this?\n\n' + '\n\n'.join(syn['introduction']) + '\n\n'
framework += '## Recurring views\n\n'
for item in syn['views']:
    framework += f"### {item['view']}\n\n{item['description']}\n\n**Qualification:** {item['qualification']}\n\n" + links(item['article_ids'])
framework += '## Questions to ask, in order\n\n'
for i, item in enumerate(syn['steps'], 1):
    framework += f"### {i}. {item['question']}\n\n{item['explanation']}\n\n" + links(item['article_ids'])
framework += '## Where the framework helps and needs resistance\n\n'
for item in syn['takeaways']:
    framework += f"### {item['title']}\n\n{item['text']}\n\n" + links(item['article_ids'])
framework += '## Worked examples\n\nReviewer-created applications of the framework, not predictions of the author\'s current views.\n\n'
for item in syn['examples']:
    framework += f"### {item['title']}\n\n{item['reading']}\n\n" + bullets(item['questions'])
    framework += f"**Caution:** {item['caution']}\n\n" + links(item['article_ids'])
write('FRAMEWORK.md', framework)

tools = '# Tools and charts\n\nChart-family counts reflect source image labels, not an exact count of every conceptual reference or a measure of forecasting value. Representative chart notes reflect actual visual inspection; all chart images remain with the original publishers.\n\n'
tools += table(['Family', 'Reports', 'Use', 'Observed labels'],
               [(t['name'], t['articles'], t['use'], ', '.join(t['labels'])) for t in load('chart-catalog.json')])
tools += '## Representative chart interpretations\n\n'
for chart in load('representative-charts.json'):
    tools += f"### {chart['alt']}\n\nReport {chart['article_id']} | {chart['date']}\n\n{chart['reviewer_note']}\n\n"
    tools += f"[Original chart]({chart['url']}) | [Article review](articles/{chart['article_id']}.md)\n\n"

class GlossaryTable(HTMLParser):
    def __init__(self):
        super().__init__()
        self.rows, self.row, self.value, self.in_cell = [], [], '', False
    def handle_starttag(self, tag, attrs):
        if tag == 'tr':
            self.row = []
        elif tag in {'td', 'th'}:
            self.in_cell, self.value = True, ''
    def handle_data(self, data):
        if self.in_cell:
            self.value += data
    def handle_endtag(self, tag):
        if tag in {'td', 'th'}:
            self.row.append(self.value)
            self.in_cell = False
        elif tag == 'tr':
            self.rows.append(self.row)

glossary = GlossaryTable()
glossary.feed(glossary_section())
tools += '## Glossary\n\n' + table(glossary.rows[0], glossary.rows[1:])
write('TOOLS-AND-CHARTS.md', tools)

method_text = '# Methodology\n\nAs of ' + method['as_of'] + '.\n\n'
for key, title in [('scope', 'Scope'), ('materiality', 'Materiality'), ('source_vintage', 'Source versions')]:
    method_text += f"## {title}\n\n{method[key]}\n\n"
method_text += '## Verdict definitions\n\n' + table(['Verdict', 'Definition'], [(LABELS[k], v) for k, v in method['verdicts'].items()])
method_text += '## Evidence and scoring rules\n\n'
method_text += ''.join(f'{i}. {rule}\n' for i, rule in enumerate(method['rules'], 1)) + '\n'
for key, title in [('peer_review', 'Review quality check'), ('external_review', 'Independent methodology review'), ('publication', 'Public edition')]:
    method_text += f"## {title}\n\n{method[key]}\n\n"
write('METHODOLOGY.md', method_text)
print(f'Built {len(reviews)} Markdown reviews, article index, and four synthesis guides.')
